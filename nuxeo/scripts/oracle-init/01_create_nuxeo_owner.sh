#!/bin/bash
# Runs once when the Oracle XE container first initialises.
# Creates both schema users using credentials passed via environment variables.

export ORACLE_HOME=/u01/app/oracle/product/11.2.0/xe
export PATH=$ORACLE_HOME/bin:$PATH
export ORACLE_SID=XE

sqlplus -S sys/${ORACLE_SYSTEM_PASSWORD}@localhost/XE as sysdba <<SQL
WHENEVER SQLERROR CONTINUE;

-- N6 schema
CREATE USER ${NUXEO_USER} IDENTIFIED BY ${NUXEO_PASSWORD}
  DEFAULT TABLESPACE USERS
  TEMPORARY TABLESPACE TEMP
  QUOTA UNLIMITED ON USERS;

GRANT CONNECT, RESOURCE, CREATE VIEW TO ${NUXEO_USER};
GRANT CREATE SEQUENCE, CREATE TABLE, CREATE TRIGGER, CREATE TYPE TO ${NUXEO_USER};
GRANT SELECT ANY DICTIONARY TO ${NUXEO_USER};
GRANT IMP_FULL_DATABASE TO ${NUXEO_USER};
GRANT EXECUTE ON SYS.DBMS_CRYPTO TO ${NUXEO_USER};

-- N7 schema (empty — populated later by clone-schema-to-owner7.sh)
CREATE USER ${NUXEO_USER7} IDENTIFIED BY ${NUXEO_PASSWORD7}
  DEFAULT TABLESPACE USERS
  TEMPORARY TABLESPACE TEMP
  QUOTA UNLIMITED ON USERS;

GRANT CONNECT, RESOURCE, CREATE VIEW TO ${NUXEO_USER7};
GRANT CREATE SEQUENCE, CREATE TABLE, CREATE TRIGGER, CREATE TYPE TO ${NUXEO_USER7};
GRANT SELECT ANY DICTIONARY TO ${NUXEO_USER7};
GRANT IMP_FULL_DATABASE TO ${NUXEO_USER7};
GRANT EXECUTE ON SYS.DBMS_CRYPTO TO ${NUXEO_USER7};

EXIT;
SQL
