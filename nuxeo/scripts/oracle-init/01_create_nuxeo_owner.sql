-- Runs once when the Oracle XE container first initialises.
-- Creates both schema users upfront so Data Pump import has a target for N7.

WHENEVER SQLERROR CONTINUE;

-- N6 schema
CREATE USER NUXEO_OWNER IDENTIFIED BY nxo_own17
  DEFAULT TABLESPACE USERS
  TEMPORARY TABLESPACE TEMP
  QUOTA UNLIMITED ON USERS;

GRANT CONNECT, RESOURCE, CREATE VIEW TO NUXEO_OWNER;
GRANT CREATE SEQUENCE, CREATE TABLE, CREATE TRIGGER, CREATE TYPE TO NUXEO_OWNER;
GRANT SELECT ANY DICTIONARY TO NUXEO_OWNER;
GRANT IMP_FULL_DATABASE TO NUXEO_OWNER;
GRANT EXECUTE ON SYS.DBMS_CRYPTO TO NUXEO_OWNER;

-- N7 schema (empty — populated later by clone-schema-to-owner7.sh)
CREATE USER NUXEO_OWNER7 IDENTIFIED BY nxo_own17
  DEFAULT TABLESPACE USERS
  TEMPORARY TABLESPACE TEMP
  QUOTA UNLIMITED ON USERS;

GRANT CONNECT, RESOURCE, CREATE VIEW TO NUXEO_OWNER7;
GRANT CREATE SEQUENCE, CREATE TABLE, CREATE TRIGGER, CREATE TYPE TO NUXEO_OWNER7;
GRANT SELECT ANY DICTIONARY TO NUXEO_OWNER7;
GRANT IMP_FULL_DATABASE TO NUXEO_OWNER7;
GRANT EXECUTE ON SYS.DBMS_CRYPTO TO NUXEO_OWNER7;

EXIT;
